// Package gen creates the deterministic, synthetic ledger used by the Fava
// reference harness. It deliberately accepts no ledger input: every account,
// label, amount, and date is produced from the fixed configuration below.
package gen

import (
	"encoding/json"
	"fmt"
	"math/big"
	"os"
	"path/filepath"
	"sort"
	"strings"
	"time"
)

// Config controls the density of the generated reference fixture. The default
// is intentionally large enough to exercise scrolling, grouping, pagination,
// currencies, lots, documents, and source navigation without being expensive.
type Config struct {
	Wallets           int `json:"wallets"`
	Reserves          int `json:"reserves"`
	Receivables       int `json:"receivables"`
	Investments       int `json:"investments"`
	Cards             int `json:"cards"`
	Loans             int `json:"loans"`
	SalesChannels     int `json:"sales_channels"`
	ExpenseCategories int `json:"expense_categories"`
	ActivityEntries   int `json:"activity_entries"`
}

// DefaultConfig is the committed synthetic-reference scale. All values are
// fixed so rerunning the generator produces byte-identical output.
var DefaultConfig = Config{
	Wallets:           16,
	Reserves:          16,
	Receivables:       10,
	Investments:       5,
	Cards:             10,
	Loans:             5,
	SalesChannels:     8,
	ExpenseCategories: 14,
	ActivityEntries:   120,
}

// Result describes the files written by Generate.
type Result struct {
	Files        []string
	Accounts     int
	Transactions int
}

type accountSpec struct {
	Name       string
	Currencies []string
}

type balanceBook map[string]map[string]*big.Rat

// Generate writes a complete synthetic reference fixture below root. Existing
// files with the same generated names are replaced; unrelated files are left
// untouched so the function cannot delete an owner's directory contents.
func Generate(root string, config Config) (Result, error) {
	config = normalizeConfig(config)
	accounts := buildAccounts(config)
	files := make(map[string]string)
	balances := make(balanceBook)

	files["main.bean"] = strings.Join([]string{
		"; Generated by tools/fixturegen. Synthetic data only.",
		"option \"title\" \"OrangeCount Dense Reference Ledger\"",
		"option \"operating_currency\" \"USD\"",
		"option \"name_assets\" \"Assets\"",
		"option \"name_liabilities\" \"Liabilities\"",
		"option \"name_equity\" \"Equity\"",
		"option \"name_income\" \"Income\"",
		"option \"name_expenses\" \"Expenses\"",
		"include \"accounts.bean\"",
		"include \"activity.bean\"",
		"include \"directives.bean\"",
		"",
	}, "\n")
	files["accounts.bean"] = renderAccounts(accounts)

	activity, transactionCount := renderActivity(accounts, config, balances)
	files["activity.bean"] = activity
	files["directives.bean"] = renderDirectives(accounts, balances, transactionCount)
	files["editor/invalid.bean"] = "2025-01-01 * \"Unclosed narration\n  Assets:Cash:Wallet01 1 USD\n"
	files["import/import-candidate.csv"] = strings.Join([]string{
		"date,payee,account,amount,currency,narration",
		"2025-06-15,Synthetic Import,Assets:Cash:Wallet01,17.25,USD,Imported coffee",
		"2025-06-16,Synthetic Import,Expenses:Operations:General,8.50,USD,Imported meal",
		"",
	}, "\n")
	files["saved-queries/account-balances.query"] = "SELECT account, balance FROM accounts ORDER BY account\n"
	files["documents/doc-001.txt"] = "Synthetic document 001 for OrangeCount reference capture.\n"
	files["documents/doc-002.txt"] = "Synthetic document 002 for nested account navigation.\n"
	files["documents/nested/doc-003.txt"] = "Synthetic nested document 003 for containment checks.\n"
	files["README.md"] = renderREADME(config, accounts, transactionCount)
	lock, err := json.MarshalIndent(struct {
		SchemaVersion int    `json:"schema_version"`
		Generator     string `json:"generator"`
		Version       string `json:"generator_version"`
		Deterministic bool   `json:"deterministic"`
		Config        Config `json:"config"`
	}{1, "tools/fixturegen", "1", true, config}, "", "  ")
	if err != nil {
		return Result{}, err
	}
	files["generator-lock.json"] = string(lock) + "\n"

	for name, content := range files {
		path := filepath.Join(root, filepath.FromSlash(name))
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			return Result{}, fmt.Errorf("create %s: %w", filepath.Dir(path), err)
		}
		if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
			return Result{}, fmt.Errorf("write %s: %w", name, err)
		}
	}
	result := Result{Accounts: len(accounts), Transactions: transactionCount}
	for name := range files {
		result.Files = append(result.Files, name)
	}
	sort.Strings(result.Files)
	return result, nil
}

// normalizeConfig applies defaults and clamps out-of-range values so the
// generator always runs on a valid config.
func normalizeConfig(config Config) Config {
	defaults := DefaultConfig
	if config.Wallets <= 0 {
		config.Wallets = defaults.Wallets
	}
	if config.Reserves <= 0 {
		config.Reserves = defaults.Reserves
	}
	if config.Receivables <= 0 {
		config.Receivables = defaults.Receivables
	}
	if config.Investments <= 0 {
		config.Investments = defaults.Investments
	}
	if config.Cards <= 0 {
		config.Cards = defaults.Cards
	}
	if config.Loans <= 0 {
		config.Loans = defaults.Loans
	}
	if config.SalesChannels <= 0 {
		config.SalesChannels = defaults.SalesChannels
	}
	if config.ExpenseCategories <= 0 {
		config.ExpenseCategories = defaults.ExpenseCategories
	}
	if config.ActivityEntries <= 0 {
		config.ActivityEntries = defaults.ActivityEntries
	}
	return config
}

func buildAccounts(config Config) []accountSpec {
	accounts := []accountSpec{
		{Name: "Equity:Opening-Balances", Currencies: []string{"USD", "EUR", "JPY", "GBP", "CAD", "CHF", "AUD", "SHARES", "BTC", "GOLD"}},
		{Name: "Equity:Adjustments", Currencies: []string{"USD"}},
		{Name: "Equity:Imported", Currencies: []string{"USD"}},
	}
	add := func(prefix string, count int, currencies []string) {
		for i := 1; i <= count; i++ {
			accounts = append(accounts, accountSpec{
				Name:       fmt.Sprintf("%s%02d", prefix, i),
				Currencies: append([]string(nil), currencies...),
			})
		}
	}
	add("Assets:Cash:Wallet", config.Wallets, []string{"USD", "EUR", "JPY", "CHF"})
	add("Assets:Cash:Reserve", config.Reserves, []string{"USD", "CAD", "GBP"})
	add("Assets:Receivables:Client", config.Receivables, []string{"USD", "EUR"})
	add("Assets:Investments:Index", config.Investments, []string{"SHARES", "USD"})
	add("Liabilities:Credit:Card", config.Cards, []string{"USD"})
	add("Liabilities:Loans:Term", config.Loans, []string{"USD"})
	add("Income:Sales:Channel", config.SalesChannels, []string{"USD"})
	add("Expenses:Operations:Category", config.ExpenseCategories, []string{"USD"})
	return accounts
}

func renderAccounts(accounts []accountSpec) string {
	var b strings.Builder
	b.WriteString("; Accounts and commodities are generated from fixed synthetic inputs.\n")
	for _, currency := range []string{"USD", "EUR", "JPY", "GBP", "CAD", "CHF", "AUD", "SHARES", "BTC", "GOLD"} {
		fmt.Fprintf(&b, "2024-01-01 commodity %s\n", currency)
	}
	b.WriteByte('\n')
	for _, account := range accounts {
		fmt.Fprintf(&b, "2024-01-01 open %s %s\n", account.Name, strings.Join(account.Currencies, ", "))
	}
	return b.String()
}

// activityWriter renders synthetic transactions into a shared builder while
// tracking the running date index and transaction count, so each activity
// phase (opening allocations, dense activity, investment lots) can be its
// own readable function.
type activityWriter struct {
	b                *strings.Builder
	balances         balanceBook
	dateIndex        int
	transactionCount int
}

// nextDate hands out strictly increasing dates from the 2024-01-02 base.
func (w *activityWriter) nextDate() string {
	date := time.Date(2024, 1, 2, 0, 0, 0, 0, time.UTC).AddDate(0, 0, w.dateIndex)
	w.dateIndex++
	return date.Format("2006-01-02")
}

// transaction writes one transaction with optional tags, links, metadata,
// and postings, and keeps the fixture's balances in sync.
func (w *activityWriter) transaction(date, flag, payee, narration string, tags, links []string, metadata string, postings ...postingSpec) {
	fmt.Fprintf(w.b, "%s %s \"%s\" \"%s\"", date, flag, payee, narration)
	for _, tag := range tags {
		fmt.Fprintf(w.b, " #%s", tag)
	}
	for _, link := range links {
		fmt.Fprintf(w.b, " ^%s", link)
	}
	w.b.WriteByte('\n')
	if metadata != "" {
		fmt.Fprintf(w.b, "  category: \"%s\"\n", metadata)
	}
	for _, posting := range postings {
		fmt.Fprintf(w.b, "  %s %s %s\n", posting.Account, posting.Amount, posting.Currency)
		addBalance(w.balances, posting.Account, posting.Currency, posting.Amount)
	}
	w.b.WriteByte('\n')
	w.transactionCount++
}

// renderActivity writes the dense deterministic activity: opening
// allocations, repeated entries, and investment lots. No network prices or
// private data are involved.
func renderActivity(accounts []accountSpec, config Config, balances balanceBook) (string, int) {
	b := &strings.Builder{}
	b.WriteString("; Dense, deterministic activity. No network prices or private data.\n")
	w := &activityWriter{b: b, balances: balances}
	w.openingAllocations(accounts)
	w.denseActivity(accounts, config.ActivityEntries)
	w.investmentLots(config.Investments)
	return b.String(), w.transactionCount
}

// openingAllocations places every declared currency on the non-cash
// accounts, producing the multi-currency and tree density the reference UI
// needs.
func (w *activityWriter) openingAllocations(accounts []accountSpec) {
	for index, account := range accounts[3:] {
		for currencyIndex, currency := range account.Currencies {
			amount := fmt.Sprintf("%d", 25+((index+currencyIndex)%17)*5)
			w.transaction(w.nextDate(), "*", "Opening Allocation", fmt.Sprintf("%s opening", account.Name), []string{"opening"}, []string{fmt.Sprintf("open-%03d", index)}, "opening", postingSpec{account.Name, amount, currency}, postingSpec{"Equity:Opening-Balances", negate(amount), currency})
		}
	}
}

// denseActivity writes repeated entries using all account families, flags,
// tags, links, and Unicode labels. Three-posting USD entries exercise
// grouped journal rows.
func (w *activityWriter) denseActivity(accounts []accountSpec, entries int) {
	flags := []string{"*", "!", "A", "B", "C", "P", "S", "T", "U", "R"}
	for i := 0; i < entries; i++ {
		account := accounts[3+i%len(accounts[3:])]
		currency := account.Currencies[i%len(account.Currencies)]
		amount := fmt.Sprintf("%d.%02d", 3+i%23, (i*7)%100)
		if w.feeEntry(account, currency, i, amount) {
			continue
		}
		w.transaction(w.nextDate(), flags[i%len(flags)], "Synthetic Counterparty", fmt.Sprintf("Dense activity %03d — café", i+1), []string{fmt.Sprintf("activity-%d", i%6)}, []string{fmt.Sprintf("batch-%03d", i%9)}, "activity", postingSpec{account.Name, amount, currency}, postingSpec{activityCounter(account, currency), negate(amount), currency})
	}
}

// feeEntry writes the periodic three-posting USD entry (with an operations
// fee) and reports whether it applied; every 11th non-expenses USD entry
// takes this shape.
func (w *activityWriter) feeEntry(account accountSpec, currency string, i int, amount string) bool {
	if i%11 != 0 || currency != "USD" || strings.HasPrefix(account.Name, "Expenses:") {
		return false
	}
	fee := fmt.Sprintf("%d.%02d", 1+i%4, (i*3)%100)
	total := addAmount(amount, fee)
	w.transaction(w.nextDate(), activityFlags[i%len(activityFlags)], "Synthetic Counterparty", fmt.Sprintf("Dense activity %03d", i+1), []string{fmt.Sprintf("activity-%d", i%6), "dense"}, []string{fmt.Sprintf("batch-%03d", i%9)}, "activity", postingSpec{account.Name, amount, currency}, postingSpec{"Expenses:Operations:Category01", fee, currency}, postingSpec{"Equity:Adjustments", negate(total), currency})
	return true
}

// activityFlags is the deterministic flag cycle used by dense activity.
var activityFlags = []string{"*", "!", "A", "B", "C", "P", "S", "T", "U", "R"}

// activityCounter picks the balancing account for a dense entry by family.
func activityCounter(account accountSpec, currency string) string {
	if currency != "USD" {
		return "Equity:Opening-Balances"
	}
	switch {
	case strings.HasPrefix(account.Name, "Assets:"):
		return "Expenses:Operations:Category01"
	case strings.HasPrefix(account.Name, "Expenses:"), strings.HasPrefix(account.Name, "Income:"):
		return "Assets:Cash:Wallet01"
	default:
		return "Equity:Opening-Balances"
	}
}

// investmentLots writes explicit cost lots so holdings and cost rendering
// are visible in the fixture.
func (w *activityWriter) investmentLots(investments int) {
	for i := 1; i <= investments; i++ {
		date := w.nextDate()
		account := fmt.Sprintf("Assets:Investments:Index%02d", i)
		units := fmt.Sprintf("%d", 4+i)
		cost := fmt.Sprintf("%d", 20+i*3)
		total := fmt.Sprintf("%d", (4+i)*(20+i*3))
		fmt.Fprintf(w.b, "%s * \"Synthetic Broker\" \"Lot purchase %02d\" #lot ^lot-%02d\n", date, i, i)
		w.b.WriteString("  lot_type: \"reference\"\n")
		fmt.Fprintf(w.b, "  %s %s SHARES {%s USD}\n", account, units, cost)
		fmt.Fprintf(w.b, "  Equity:Opening-Balances -%s USD\n\n", total)
		addBalance(w.balances, account, "SHARES", units)
		addBalance(w.balances, "Equity:Opening-Balances", "USD", "-"+total)
		w.transactionCount++
	}
}

type postingSpec struct {
	Account  string
	Amount   string
	Currency string
}

func renderDirectives(accounts []accountSpec, balances balanceBook, transactionCount int) string {
	var b strings.Builder
	b.WriteString("; Source-preserving directives for events, documents, queries, and options.\n")
	fmt.Fprintf(&b, "2025-06-20 event \"milestone\" \"dense-fixture-%d\"\n", transactionCount)
	b.WriteString("2025-06-21 query \"saved-overview\" \"SELECT account, balance FROM accounts ORDER BY account\"\n")
	b.WriteString("2025-06-22 custom \"review-state\" \"pending\" \"synthetic\"\n")
	b.WriteString("2025-06-23 custom \"risk-score\" 3.5 USD true\n")
	b.WriteString("2025-06-24 note Assets:Cash:Wallet01 \"Synthetic note for source navigation and context.\"\n")
	b.WriteString("2025-06-25 document Assets:Cash:Wallet01 \"documents/doc-001.txt\" #evidence ^doc-001\n")
	b.WriteString("2025-06-26 document Assets:Cash:Reserve01 \"documents/doc-002.txt\" #evidence ^doc-002\n")
	b.WriteString("2025-06-27 document Assets:Receivables:Client01 \"documents/nested/doc-003.txt\" #nested ^doc-003\n")
	// Linked/discovered document transactions exercise the journal D/L chips
	// and linked/discovered row classes (Fava: #linked / #discovered tags on a
	// document entry, shown as show-document children).
	b.WriteString("2025-06-27 document Assets:Cash:Wallet01 \"documents/doc-001.txt\" #linked ^doc-linked\n")
	b.WriteString("2025-06-27 document Assets:Cash:Reserve01 \"documents/doc-002.txt\" #discovered ^doc-discovered\n")
	b.WriteString("2025-06-28 price EUR 1.10 USD\n")
	b.WriteString("2025-06-28 price JPY 0.0075 USD\n")
	b.WriteString("2025-06-28 price GBP 1.27 USD\n")
	b.WriteString("2025-06-28 price CAD 0.74 USD\n")
	b.WriteString("2025-06-28 price CHF 1.11 USD\n")
	b.WriteString("2025-06-28 price AUD 0.66 USD\n")
	b.WriteString("2025-06-28 price SHARES 28.50 USD\n")
	b.WriteString("2025-06-28 price BTC 62000 USD\n")
	b.WriteString("2025-06-28 price GOLD 2300 USD\n")
	// One exact balance assertion demonstrates the balance directive without
	// relying on hand-maintained amounts.
	if amount := balanceText(balances, "Assets:Cash:Wallet01", "USD"); amount != "" {
		fmt.Fprintf(&b, "2025-06-29 balance Assets:Cash:Wallet01 %s USD\n", amount)
	}
	b.WriteString("2025-06-30 close Liabilities:Credit:Card01\n")
	_ = accounts
	return b.String()
}

