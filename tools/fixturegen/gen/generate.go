func addBalance(book balanceBook, account, currency, amount string) {
	value, ok := new(big.Rat).SetString(amount)
	if !ok {
		panic("fixture generator produced invalid amount: " + amount)
	}
	if book[account] == nil {
		book[account] = make(map[string]*big.Rat)
	}
	if book[account][currency] == nil {
		book[account][currency] = new(big.Rat)
	}
	book[account][currency].Add(book[account][currency], value)
}

func balanceText(book balanceBook, account, currency string) string {
	value := book[account][currency]
	if value == nil {
		return ""
	}
	if value.IsInt() {
		return value.Num().String()
	}
	return strings.TrimRight(strings.TrimRight(value.FloatString(2), "0"), ".")
}

func negate(amount string) string {
	if strings.HasPrefix(amount, "-") {
		return strings.TrimPrefix(amount, "-")
	}
	return "-" + amount
}

func addAmount(left, right string) string {
	l, ok := new(big.Rat).SetString(left)
	if !ok {
		panic("invalid fixture amount: " + left)
	}
	r, ok := new(big.Rat).SetString(right)
	if !ok {
		panic("invalid fixture amount: " + right)
	}
	l.Add(l, r)
	if l.IsInt() {
		return l.Num().String()
	}
	return strings.TrimRight(strings.TrimRight(l.FloatString(2), "0"), ".")
}
