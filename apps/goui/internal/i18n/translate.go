var englishPrefixes []string

func init() {
	for _, pair := range englishPairs {
		english[pair[0]] = pair[1]
		englishPrefixes = append(englishPrefixes, pair[0])
	}
	// Longest prefixes must win so that complete messages take precedence over
	// shorter shared labels.
	sort.Slice(englishPrefixes, func(i, j int) bool { return len(englishPrefixes[i]) > len(englishPrefixes[j]) })
}

// Normalize returns the supported locale, defaulting unknown values to
// Simplified Chinese to preserve the application's existing behavior.
func Normalize(locale string) string {
	if locale == English {
		return English
	}
	return SimplifiedChinese
}

// Text translates an application-owned Chinese string. It also translates a
// known prefix for status strings that append an operating-system error. The
// caller must not pass ledger data or arbitrary source text here.
func Text(locale, source string) string {
	if Normalize(locale) != English {
		return source
	}
	if translated, ok := english[source]; ok {
		return translated
	}
	for _, prefix := range englishPrefixes {
		if strings.HasPrefix(source, prefix) {
			return english[prefix] + source[len(prefix):]
		}
	}
	return source
}
